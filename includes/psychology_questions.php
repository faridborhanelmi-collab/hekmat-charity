    ];

    return $q;
}

/**
 * همگام‌سازی و ثبت خودکار نتایج آزمون در پرونده دانش‌آموز (student_psychology)
 */
function syncInterviewScoresToStudentPsychology($pdo, $student_id, $test_type, $scores) {
    if (empty($student_id) || empty($scores) || !($pdo instanceof PDO)) {
        return false;
    }

    $chk = $pdo->prepare("SELECT student_id FROM student_psychology WHERE student_id = ?");
    $chk->execute([$student_id]);
    $exists = (bool)$chk->fetch();

    if ($test_type === 'comprehensive_battery') {
        $g = $scores['gardner'] ?? [];
        $e = $scores['seiq'] ?? [];
        $a = $scores['amq'] ?? [];
        $s = $scores['scl90'] ?? [];

        $mi_total = isset($g['total_score']) ? intval($g['total_score']) : null;
        $mi_grade = $g['grade'] ?? null;

        $eq_total = isset($e['total_score']) ? intval($e['total_score']) : null;
        $eq_grade = $e['grade'] ?? null;

        $hermans_score = isset($a['total_score']) ? intval($a['total_score']) : null;
        $hermans_grade = $a['level'] ?? null;

        $scl_sub = $s['subscales'] ?? [];
        $scl90_so = isset($scl_sub['so']['score']) ? floatval($scl_sub['so']['score']) : null;
        $scl90_ob = isset($scl_sub['ob']['score']) ? floatval($scl_sub['ob']['score']) : null;
        $scl90_is = isset($scl_sub['is']['score']) ? floatval($scl_sub['is']['score']) : null;
        $scl90_de = isset($scl_sub['de']['score']) ? floatval($scl_sub['de']['score']) : null;
        $scl90_an = isset($scl_sub['an']['score']) ? floatval($scl_sub['an']['score']) : null;
        $scl90_ag = isset($scl_sub['ag']['score']) ? floatval($scl_sub['ag']['score']) : null;
        $scl90_ph = isset($scl_sub['ph']['score']) ? floatval($scl_sub['ph']['score']) : null;
        $scl90_pa = isset($scl_sub['pa']['score']) ? floatval($scl_sub['pa']['score']) : null;
        $scl90_ps = isset($scl_sub['ps']['score']) ? floatval($scl_sub['ps']['score']) : null;
        $scl90_gsi = isset($s['gsi']) ? floatval($s['gsi']) : null;
        $scl90_pst = isset($s['pst']) ? intval($s['pst']) : null;
        $scl90_psdi = isset($s['psdi']) ? floatval($s['psdi']) : null;
        $scl90_risk = $s['health_status'] ?? 'Normal';

        $final_grade = $scores['final_grade'] ?? $scores['grade'] ?? 'B';
        $recommendation = $scores['composite']['executive_summary'] ?? $scores['recommendation'] ?? '';

        if ($exists) {
            $up = $pdo->prepare("
                UPDATE student_psychology SET
                    hermans_score = ?, hermans_grade = ?,
                    scl90_so = ?, scl90_ob = ?, scl90_is = ?, scl90_de = ?, scl90_an = ?, scl90_ag = ?, scl90_ph = ?, scl90_pa = ?, scl90_ps = ?,
                    scl90_gsi = ?, scl90_pst = ?, scl90_psdi = ?, scl90_risk = ?,
                    mi_total = ?, mi_grade = ?,
                    eq_total = ?, eq_grade = ?,
                    final_grade = ?, recommendation = ?
                WHERE student_id = ?
            ");
            return $up->execute([
                $hermans_score, $hermans_grade,
                $scl90_so, $scl90_ob, $scl90_is, $scl90_de, $scl90_an, $scl90_ag, $scl90_ph, $scl90_pa, $scl90_ps,
                $scl90_gsi, $scl90_pst, $scl90_psdi, $scl90_risk,
                $mi_total, $mi_grade,
                $eq_total, $eq_grade,
                $final_grade, $recommendation,
                $student_id
            ]);
        } else {
            $ins = $pdo->prepare("
                INSERT INTO student_psychology (
                    student_id,
                    hermans_score, hermans_grade,
                    scl90_so, scl90_ob, scl90_is, scl90_de, scl90_an, scl90_ag, scl90_ph, scl90_pa, scl90_ps,
                    scl90_gsi, scl90_pst, scl90_psdi, scl90_risk,
                    mi_total, mi_grade,
                    eq_total, eq_grade,
                    final_grade, recommendation
                ) VALUES (
                    ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
                )
            ");
            return $ins->execute([
                $student_id,
                $hermans_score, $hermans_grade,
                $scl90_so, $scl90_ob, $scl90_is, $scl90_de, $scl90_an, $scl90_ag, $scl90_ph, $scl90_pa, $scl90_ps,
                $scl90_gsi, $scl90_pst, $scl90_psdi, $scl90_risk,
                $mi_total, $mi_grade,
                $eq_total, $eq_grade,
                $final_grade, $recommendation
            ]);
        }
    } else {
        if (!$exists) {
            $ins = $pdo->prepare("INSERT INTO student_psychology (student_id) VALUES (?)");
            $ins->execute([$student_id]);
        }

        if ($test_type === 'gardner_mit') {
            $up = $pdo->prepare("UPDATE student_psychology SET mi_total = ?, mi_grade = ?, recommendation = COALESCE(recommendation, ?) WHERE student_id = ?");
            return $up->execute([$scores['total_score'] ?? null, $scores['grade'] ?? 'B', $scores['recommendation'] ?? '', $student_id]);
        } elseif ($test_type === 'emotional_seiq') {
            $up = $pdo->prepare("UPDATE student_psychology SET eq_total = ?, eq_grade = ?, recommendation = COALESCE(recommendation, ?) WHERE student_id = ?");
            return $up->execute([$scores['total_score'] ?? null, $scores['grade'] ?? 'B', $scores['recommendation'] ?? '', $student_id]);
        } elseif ($test_type === 'hermans_amq') {
            $up = $pdo->prepare("UPDATE student_psychology SET hermans_score = ?, hermans_grade = ?, recommendation = COALESCE(recommendation, ?) WHERE student_id = ?");
            return $up->execute([$scores['total_score'] ?? null, $scores['level'] ?? 'متوسط', $scores['recommendation'] ?? '', $student_id]);
        } elseif ($test_type === 'scl90_mental') {
            $scl_sub = $scores['subscales'] ?? [];
            $up = $pdo->prepare("
                UPDATE student_psychology SET
                    scl90_so = ?, scl90_ob = ?, scl90_is = ?, scl90_de = ?, scl90_an = ?, scl90_ag = ?, scl90_ph = ?, scl90_pa = ?, scl90_ps = ?,
                    scl90_gsi = ?, scl90_pst = ?, scl90_psdi = ?, scl90_risk = ?, recommendation = COALESCE(recommendation, ?)
                WHERE student_id = ?
            ");
            return $up->execute([
                $scl_sub['so']['score'] ?? null, $scl_sub['ob']['score'] ?? null, $scl_sub['is']['score'] ?? null,
                $scl_sub['de']['score'] ?? null, $scl_sub['an']['score'] ?? null, $scl_sub['ag']['score'] ?? null,
                $scl_sub['ph']['score'] ?? null, $scl_sub['pa']['score'] ?? null, $scl_sub['ps']['score'] ?? null,
                $scores['gsi'] ?? null, $scores['pst'] ?? null, $scores['psdi'] ?? null, $scores['health_status'] ?? 'Normal',
                $scores['recommendation'] ?? '', $student_id
            ]);
        }
    }
    return false;
}

