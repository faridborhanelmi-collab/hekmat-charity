/**
 * تولید ۵ سوال اختصاصی برای مصاحبه حضوری بر اساس کارنامه داوطلب
 */
function generateTargetedInterviewQuestions($t1, $t2, $seiq, $amq, $scl90) {
    $q = [];

    // سوال ۱: بر مبنای استعداد برتر گاردنر
    $q[] = [
        'topic' => 'سنجش عمق استعداد برتر',
        'question' => "با توجه به علاقه و مهارت بالایت در حوزه استعدادیابی، یک تجربه واقعی که در آن مسئله‌ای پیچیده را با این توانمندی حل کردی برایمان تعریف کن."
    ];

    // سوال ۲: بر مبنای هوش هیجانی
    $eq_score = $seiq['total_score'] ?? 100;
    if ($eq_score > 125) {
        $q[] = [
            'topic' => 'مدیریت بحران و رهبری عاطفی',
            'question' => "وقتی در یک جمع یا تیم، افراد دچار تنش و اختلاف‌نظر شدید می‌شوند، تو معمولاً چطور فضا را آرام می‌کنی و تعارض را حل می‌کنی؟"
        ];
    } else {
        $q[] = [
            'topic' => 'شناخت خود و واکنش به فشار',
            'question' => "وقتی کاری طبق برنامه‌ات پیش نمی‌رود و احساس ناکامی یا عصبانیت می‌کنی، چه تکنیکی برای بازیابی آرامش خودت داری؟"
        ];
    }

    // سوال ۳: بر مبنای انگیزه پیشرفت هرمنس
    $amq_score = $amq['total_score'] ?? 80;
    if ($amq_score > 90) {
        $q[] = [
            'topic' => 'اهداف بلندپروازانه و افق ۵ ساله',
            'question' => "نشانه‌های یک انگیزه پیشرفت بسیار قوی در پاسخ‌هایت دیده می‌شود؛ بزرگ‌ترین هدفی که برای ۵ سال آینده خودت در نظر گرفتی چیست و برایش چه برنامه‌ای داری؟"
        ];
    } else {
        $q[] = [
            'topic' => 'پشتکار در وظایف دشوار',
            'question' => "اگر با تکلیفی روبرو شوی که در نگاه اول خیلی دشوار و زمان‌بر به نظر برسد، چگونه انگیزه‌ات را برای ادامه دادن تا انتها حفظ می‌کنی؟"
        ];
    }

    // سوال ۴: بر مبنای سازگاری و آرامش روان
    $gsi = $scl90['gsi'] ?? 0.5;
    if ($gsi < 0.8) {
        $q[] = [
            'topic' => 'پایداری روانی و تاب‌آوری',
            'question' => "روحیه‌ات بسیار آرام و مسلط ارزیابی شده؛ چه عادت‌های روزمره‌ای (ورزش، مطالعه، خلوت، خواب) به حفظ این آرامش کمک می‌کند؟"
        ];
    } else {
        $q[] = [
            'topic' => 'حمایت‌پذیری و گفتگو',
            'question' => "در مواجهه با دغدغه‌های تحصیلی و ذهنی، بیشتر ترجیح می‌دهی با چه کسانی صحبت کنی و بنیاد چطور می‌تواند پشتیبان آرامش تو باشد؟"
        ];
    }

    // سوال ۵: تعهد و چشم‌انداز عضویت در بنیاد حکمت
    $q[] = [
        'topic' => 'مسئولیت اجتماعی و نقش‌آفرینی در حکمت',
