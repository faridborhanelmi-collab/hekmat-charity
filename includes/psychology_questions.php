/**
 * ۳. موتور نمره‌گذاری چک‌لیست سلامت روان SCL-90-R
 */
function calculateSCL90Scores($answers) {
    $questions = getSCL90Questions();
    $scales = [
        'somatization' => ['title' => 'شکایات جسمانی (SOM)', 'items' => [1,4,12,27,40,42,48,49,51,52,55,57,87], 'sum' => 0],
        'obsessive' => ['title' => 'وسواس فکری-عملی (O-C)', 'items' => [3,9,10,28,38,45,46,50,54,65], 'sum' => 0],
        'interpersonal' => ['title' => 'حساسیت بین‌فردی (I-S)', 'items' => [6,21,34,36,37,41,60,61,69,73], 'sum' => 0],
        'depression' => ['title' => 'افسردگی (DEP)', 'items' => [5,14,15,20,22,26,29,30,32,53,58,71,77,79,85], 'sum' => 0],
        'anxiety' => ['title' => 'اضطراب (ANX)', 'items' => [2,17,23,31,33,39,56,72,78,80,86], 'sum' => 0],
        'hostility' => ['title' => 'پرخاشگری و خصومت (HOS)', 'items' => [11,24,63,67,74,81], 'sum' => 0],
        'phobic' => ['title' => 'ترس مرضی و فوبیا (PHOB)', 'items' => [13,25,47,70,75,82], 'sum' => 0],
        'paranoid' => ['title' => 'افکار پارانوئیدی (PAR)', 'items' => [8,18,43,68,76,83], 'sum' => 0],
        'psychoticism' => ['title' => 'روان‌پریشی و انزوا (PSY)', 'items' => [7,16,35,62,84,88,90], 'sum' => 0],
        'additional' => ['title' => 'عادات خواب و تغذیه', 'items' => [19,44,59,64,66,89], 'sum' => 0]
    ];

    $total_sum = 0;
    $positive_count = 0;

    foreach ($questions as $q) {
        $qid = (string)$q['id'];
        $val = isset($answers[$qid]) ? intval($answers[$qid]) : 0;
        if ($val < 0 || $val > 4) $val = 0;

        $total_sum += $val;
        if ($val > 0) $positive_count++;

        foreach ($scales as $k => $s) {
            if (in_array($q['id'], $s['items'])) {
                $scales[$k]['sum'] += $val;
            }
        }
    }

    $gsi = round($total_sum / 90, 2); // شاخص کلی شدت بیماری (GSI)
    $pst = $positive_count; // تعداد علائم مثبت (PST)
    $psdi = $pst > 0 ? round($total_sum / $pst, 2) : 0; // شاخص درماندگی علائم مثبت

    $dims = [];
    foreach ($scales as $k => $s) {
        $count = count($s['items']);
        $mean = $count > 0 ? round($s['sum'] / $count, 2) : 0;
        $dims[$k] = [
            'title' => $s['title'],
            'raw' => $s['sum'],
            'mean' => $mean,
            'count' => $count,
            'percentage' => round(($s['sum'] / ($count * 4)) * 100)
        ];
    }

    // تفسیر بر اساس شاخص GSI
    $health_status = 'نرمال و بسیار آرام';
    $grade = 'A';
    if ($gsi < 0.8) {
        $health_status = 'سلامت روانی مطلوب و آرامش خاطر';
        $grade = 'A';
    } elseif ($gsi < 1.5) {
        $health_status = 'تنش‌ها و استرس‌های خفیف تا متوسط روزمره';
        $grade = 'B';
    } else {
        $health_status = 'نشانه‌هایی از خستگی روحی و نیازمند مشاوره حمایتی';
        $grade = 'C';
    }

    $recommendation = "شاخص شدت کلی (GSI) داوطلب {$gsi} ارزیابی شد که در محدوده «{$health_status}» قرار دارد. تعداد نشانه‌های گزارش‌شده {$pst} از ۹۰ مورد است.";

    return [
        'test_type' => 'scl90_mental',
        'test_title' => 'چک‌لیست علائم و سلامت روان (SCL-90-R)',
        'total_score' => $total_sum,
        'total_max' => 360,
        'gsi' => $gsi,
        'pst' => $pst,
        'psdi' => $psdi,
        'overall_percentage' => round(($total_sum / 360) * 100),
        'grade' => $grade,
        'dimensions' => $dims,
        'health_status' => $health_status,
        'recommendation' => $recommendation
    ];
}

/**
 * ۴. موتور نمره‌گذاری پرسشنامه انگیزه پیشرفت هرمنس AMQ (۲۹ سوال، نمره بین ۲۹ تا ۱۱۶)
 */
function calculateAMQScores($answers) {
    $questions = getAMQQuestions();
    $total_score = 0;

    foreach ($questions as $q) {
        $qid = (string)$q['id'];
        $val = isset($answers[$qid]) ? intval($answers[$qid]) : 2;
        if ($val < 1 || $val > 4) $val = 2;
        $total_score += $val;
    }

    // بر اساس نرم انگیزه پیشرفت هرمنس:
    // نمره زیر ۶۵: انگیزه پیشرفت پایین
    // نمره ۶۶ تا ۸۴: انگیزه پیشرفت متوسط
    // نمره ۸۵ تا ۱۰۰: انگیزه پیشرفت بالا
    // نمره بالای ۱۰۰: انگیزه پیشرفت عالی و سرآمد
    $level = 'متوسط';
    $grade = 'B';
    if ($total_score >= 100) {
        $level = 'فوق‌العاده و بسیار سرآمد';
        $grade = 'A+';
    } elseif ($total_score >= 85) {
        $level = 'بالا و آینده‌نگر';
        $grade = 'A';
    } elseif ($total_score >= 66) {
        $level = 'متوسط و نیازمند انگیزش';
        $grade = 'B';
    } else {
        $level = 'پایین و نیازمند تقویت اراده';
        $grade = 'C';
    }

    $overall_pct = round((($total_score - 29) / (116 - 29)) * 100);
    $recommendation = "نمره انگیزه پیشرفت داوطلب {$total_score} از ۱۱۶ ({$overall_pct}٪) برآورد گردید که در سطح «{$level}» ارزیابی می‌شود. این داوطلب پشتکار و روحیه تلاش " . ($grade === 'A+' || $grade === 'A' ? 'بسیار بالایی' : 'مطلوبی') . " در تحقق اهداف دارد.";

    return [
        'test_type' => 'hermans_amq',
        'test_title' => 'پرسشنامه انگیزه پیشرفت هرمنس',
        'total_score' => $total_score,
        'total_max' => 116,
        'overall_percentage' => $overall_pct,
        'grade' => $grade,
        'level' => $level,
        'dimensions' => [
            'aspiration' => ['title' => 'سطح آرزوها و اهداف بلند', 'score' => round($total_score * 0.35), 'percentage' => $overall_pct],
            'perseverance' => ['title' => 'پشتکار و مقاومت در برابر موانع', 'score' => round($total_score * 0.35), 'percentage' => $overall_pct],
            'future_orientation' => ['title' => 'دوراندیشی و آینده‌نگری', 'score' => round($total_score * 0.30), 'percentage' => $overall_pct]
        ],
        'recommendation' => $recommendation
    ];
}


/**
 * ==============================================================================
 * موتور محاسبه و تلفیق جامع پکیج ۴ آزمون روانسنجی بنیاد حکمت
 * ==============================================================================
 */
function calculateComprehensiveBatteryScores($all_answers) {
    // تفکیک پاسخ‌ها بر اساس مراحل
    $gardner_answers = $all_answers['gardner_mit'] ?? $all_answers;
    $seiq_answers = $all_answers['emotional_seiq'] ?? $all_answers;
    $amq_answers = $all_answers['hermans_amq'] ?? $all_answers;
    $scl90_answers = $all_answers['scl90_mental'] ?? $all_answers;

    $gardner_res = calculateGardnerScores($gardner_answers);
    $seiq_res = calculateSEIQScores($seiq_answers);
    $amq_res = calculateAMQScores($amq_answers);
    $scl90_res = calculateSCL90Scores($scl90_answers);

    // محاسبه شاخص جامع استعداد بنیاد حکمت (Hekmat Talent Index - HTI)
    // وزن‌دهی: هوش‌های گاردنر ۳۵٪ + هوش هیجانی ۲۵٪ + انگیزه پیشرفت ۲۵٪ + پایداری روان ۱۵٪
    $gardner_pct = $gardner_res['overall_percentage'] ?? 50;
    $seiq_pct = $seiq_res['overall_percentage'] ?? 50;
    $amq_pct = $amq_res['overall_percentage'] ?? 50;
    $scl90_gsi = $scl90_res['gsi'] ?? 0.5;
    
    // تبدیل GSI به درصد سلامت روان (GSI پایین‌تر = سلامت بالاتر)
    // GSI از 0 تا 4 است. GSI زیر 0.8 بسیار عالی (100-80%)
    $mental_wellness_pct = max(10, min(100, round((1 - ($scl90_gsi / 2.5)) * 100)));

    $hti = round(($gardner_pct * 0.35) + ($seiq_pct * 0.25) + ($amq_pct * 0.25) + ($mental_wellness_pct * 0.15));

    $final_grade = 'B';
    if ($hti >= 88) $final_grade = 'A+';
    elseif ($hti >= 78) $final_grade = 'A';
    elseif ($hti >= 65) $final_grade = 'B+';
    elseif ($hti >= 50) $final_grade = 'B';
    else $final_grade = 'C';

    // تولید سیمای روانشناختی و مصاحبه یکپارچه
    $composite_profile = generateCompositePsychologicalNarrative($gardner_res, $seiq_res, $amq_res, $scl90_res, $hti, $final_grade);

    return [
        'test_type' => 'comprehensive_battery',
        'test_title' => 'پکیج جامع ۴ آزمون استعدادیابی و روانسنجی',
        'is_battery' => true,
        'hti' => $hti,
        'final_grade' => $final_grade,
        'total_score' => $hti,
        'total_max' => 100,
        'overall_percentage' => $hti,
        'grade' => $final_grade,
        'gardner' => $gardner_res,
        'seiq' => $seiq_res,
        'amq' => $amq_res,
        'scl90' => $scl90_res,
        'mental_wellness_pct' => $mental_wellness_pct,
        'composite' => $composite_profile,
        'recommendation' => $composite_profile['executive_summary']
    ];
}

