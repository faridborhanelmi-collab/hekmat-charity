/**
 * دریافت مشخصات و سوالات یک آزمون مشخص
 */
function getTestDefinition($test_type = 'gardner_mit') {
    $tests = getAllAvailableTests();
    if (!isset($tests[$test_type])) {
        $test_type = 'gardner_mit';
    }
    $def = $tests[$test_type];

    switch ($test_type) {
        case 'comprehensive_battery':
            $def['is_battery'] = true;
            $def['stages_data'] = [
                'gardner_mit' => getGardnerMITQuestions(),
                'emotional_seiq' => getSEIQQuestions(),
                'hermans_amq' => getAMQQuestions(),
                'scl90_mental' => getSCL90Questions()
            ];
            // برای نمایش اولیه سوالات مرحله اول
            $def['questions'] = getGardnerMITQuestions();
            $def['default_options'] = getGardnerMITOptions();
            break;
        case 'gardner_mit':
            $def['questions'] = getGardnerMITQuestions();
            $def['default_options'] = getGardnerMITOptions();
            break;
        case 'emotional_seiq':
            $def['questions'] = getSEIQQuestions();
            $def['default_options'] = getSEIQDefaultOptions();
            break;
        case 'scl90_mental':
            $def['questions'] = getSCL90Questions();
            $def['default_options'] = getSCL90Options();
            break;
        case 'hermans_amq':
            $def['questions'] = getAMQQuestions();
            $def['default_options'] = []; // هر سوال گزینه‌های اختصاصی دارد
            break;
    }

    return $def;
}

