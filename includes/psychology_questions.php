/**
 * ۱. موتور نمره‌گذاری آزمون هوش‌های چندگانه گاردنر (۸۰ سوال، مقیاس ۵ تایی، ماکزیمم نمره ۵۰ در هر هوش)
 */
function calculateGardnerScores($answers) {
    $questions = getGardnerMITQuestions();
    $dims = [
        'linguistic' => ['title' => 'هوش کلامی و زبانی', 'raw' => 0, 'max' => 50, 'count' => 10],
        'logical' => ['title' => 'هوش منطقی و ریاضی', 'raw' => 0, 'max' => 50, 'count' => 10],
        'spatial' => ['title' => 'هوش دیداری و فضایی', 'raw' => 0, 'max' => 50, 'count' => 10],
        'kinesthetic' => ['title' => 'هوش بدنی و حرکتی', 'raw' => 0, 'max' => 50, 'count' => 10],
        'musical' => ['title' => 'هوش موسیقیایی', 'raw' => 0, 'max' => 50, 'count' => 10],
        'interpersonal' => ['title' => 'هوش بین‌فردی (اجتماعی)', 'raw' => 0, 'max' => 50, 'count' => 10],
        'intrapersonal' => ['title' => 'هوش درون‌فردی (خودشناسی)', 'raw' => 0, 'max' => 50, 'count' => 10],
        'naturalistic' => ['title' => 'هوش طبیعت‌گرا', 'raw' => 0, 'max' => 50, 'count' => 10]
    ];

    $total_score = 0;
    foreach ($questions as $q) {
        $qid = (string)$q['id'];
        $val = isset($answers[$qid]) ? intval($answers[$qid]) : 3;
        if ($val < 1 || $val > 5) $val = 3;

        $dim = $q['dimension'];
        if (isset($dims[$dim])) {
            $dims[$dim]['raw'] += $val;
            $total_score += $val;
        }
    }

    $ranking = [];
    foreach ($dims as $key => $d) {
        $percentage = round(($d['raw'] / $d['max']) * 100);
        $dims[$key]['percentage'] = $percentage;
        $ranking[] = [
            'key' => $key,
            'title' => $d['title'],
            'score' => $d['raw'],
            'percentage' => $percentage
        ];
    }

    usort($ranking, function($a, $b) {
        return $b['score'] <=> $a['score'];
    });

    $overall_pct = round(($total_score / 400) * 100);
    $grade = 'B';
    if ($overall_pct >= 85) $grade = 'A+';
    elseif ($overall_pct >= 75) $grade = 'A';
    elseif ($overall_pct >= 60) $grade = 'B+';
    elseif ($overall_pct >= 45) $grade = 'B';
    else $grade = 'C';

    $top1 = $ranking[0]['title'];
    $top2 = $ranking[1]['title'];
    $recommendation = "استعدادهای بارز داوطلب در حوزه‌های «{$top1}» و «{$top2}» شناسایی گردید. پیشنهاد می‌شود در مصاحبه حضوری محور گفتگو بر روی هدایت تحصیلی و شغلی متناسب با این استعدادها متمرکز شود.";

    return [
        'test_type' => 'gardner_mit',
        'test_title' => 'آزمون هوش‌های چندگانه گاردنر',
        'total_score' => $total_score,
        'total_max' => 400,
        'overall_percentage' => $overall_pct,
        'grade' => $grade,
        'dimensions' => $dims,
        'top_talents' => array_slice($ranking, 0, 3),
        'recommendation' => $recommendation
    ];
}

